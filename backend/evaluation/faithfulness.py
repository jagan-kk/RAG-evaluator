import os
from dotenv import load_dotenv
from openai import OpenAI
import ollama

load_dotenv()

openrouter_client = OpenAI(
    base_url="https://openrouter.ai/api/v1",
    api_key=os.getenv("OPENROUTER_API_KEY")
)

PROMPT = """
You are evaluating the faithfulness of an answer generated by an RAG system.

Your task is to determine whether the answer is fully supported by the provided context.

Context:
{context}

Answer:
{answer}

Rules:
1. Check every factual claim in the answer.
2. A claim is faithful only if it is supported by the context.
3. If the answer contains information that is not supported by the context, it is not fully faithful.
4. Do not use your own knowledge.
5. Return only a score from 0 to 1.
6. 1 means completely faithful.
7. 0 means completely unsupported.
"""


class Faithfulness:

    def evaluate(self, context, answer, provider="openrouter"):

        prompt = PROMPT.format(context=context, answer=answer)

        if provider == "ollama":
            response = ollama.generate(
                model="qwen3.5:4b",
                prompt=prompt
            )
            score_str = response["response"].strip()
        else:
            response = openrouter_client.chat.completions.create(
                model="liquid/lfm-2.5-2.6b:free",
                messages=[
                    {
                        "role": "user",
                        "content": prompt
                    }
                ]
            )
            score_str = response.choices[0].message.content.strip()

        return float(score_str)
